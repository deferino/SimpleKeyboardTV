#!/usr/bin/env python3
"""Generates the Simple Keyboard TV launcher icon, monochrome icon, TV banner and preview art.

One geometry (below) feeds every output, so the Android vectors, the SVG and the PNGs always match.
Needs Pillow (PNG output only). Usage: python scripts/gen_icons.py
Outputs (paths relative to the repo root):
  app/src/main/res/drawable-v26/ic_launcher_foreground.xml
  app/src/main/res/drawable-v26/ic_launcher_monochrome.xml
  app/src/main/res/drawable/ic_launcher.xml            (legacy, API < 26)
  app/src/main/res/drawable-xhdpi/ic_banner.png        (640x360 px = 320x180 dp, Android TV banner)
  icons/icon.svg, icons/icon-512.png, icons/banner.png
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")

BG = "#14202B"        # icon background / banner background
BODY = "#EEF3F8"      # keyboard body
KEY = "#2A3B4D"       # keys
FOCUS = "#00D8F0"     # D-pad focused key (accent)
ACCENT = "#00D8F0"

# --- geometry in a 108x108 viewport (Android adaptive-icon grid; safe zone = centre 66x66) ------
BODY_RECT = (26.0, 37.0, 56.0, 34.0, 6.0)          # x, y, w, h, radius
KW, KH, GAP = 10.0, 7.0, 2.6667
X0 = 30.0
ROW_Y = (41.0, 51.5, 62.0)


def keys():
    """Returns [(x, y, w, h, r, kind)]; kind is 'key' or 'focus'."""
    out = []
    for row in (0, 1):
        for i in range(4):
            x = X0 + i * (KW + GAP)
            if row == 1 and i == 1:
                out.append((x - 1.2, ROW_Y[row] - 1.2, KW + 2.4, KH + 2.4, 2.2, "focus"))
            else:
                out.append((x, ROW_Y[row], KW, KH, 1.6, "key"))
    out.append((X0, ROW_Y[2], KW, KH, 1.6, "key"))
    out.append((X0 + KW + GAP, ROW_Y[2], 22.6667, KH, 1.6, "key"))
    out.append((X0 + KW + GAP + 22.6667 + GAP, ROW_Y[2], KW, KH, 1.6, "key"))
    return out


def rrect_path(x, y, w, h, r):
    f = lambda v: ("%.3f" % v).rstrip("0").rstrip(".")
    return (f"M{f(x + r)},{f(y)}H{f(x + w - r)}A{f(r)},{f(r)} 0 0 1 {f(x + w)},{f(y + r)}"
            f"V{f(y + h - r)}A{f(r)},{f(r)} 0 0 1 {f(x + w - r)},{f(y + h)}H{f(x + r)}"
            f"A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y + h - r)}V{f(y + r)}A{f(r)},{f(r)} 0 0 1 {f(x + r)},{f(y)}Z")


def vector(width_dp, body, extra_groups=""):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/gen_icons.py - edit the script, not this file. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{width_dp}dp"\n    android:height="{width_dp}dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f'{body}</vector>\n')


def path_xml(data, color=None, extra=""):
    fill = f'        android:fillColor="{color}"\n' if color else ""
    return f'    <path\n{fill}{extra}        android:pathData="{data}"/>\n'


def foreground_xml():
    s = path_xml(rrect_path(*BODY_RECT), BODY)
    k = [rrect_path(*kk[:5]) for kk in keys() if kk[5] == "key"]
    s += path_xml("".join(k), KEY)
    f = [rrect_path(*kk[:5]) for kk in keys() if kk[5] == "focus"]
    s += path_xml("".join(f), FOCUS)
    return s


def monochrome_xml():
    # body with the keys punched out (even-odd), so themed icons keep the keyboard readable
    data = rrect_path(*BODY_RECT) + "".join(rrect_path(*kk[:5]) for kk in keys())
    return path_xml(data, "#FFFFFF", '        android:fillType="evenOdd"\n')


def legacy_xml():
    bg = path_xml(rrect_path(0, 0, 108, 108, 24), BG)
    grp = ('    <group\n        android:scaleX="1.3"\n        android:scaleY="1.3"\n'
           '        android:translateX="-16.2"\n        android:translateY="-16.2">\n'
           + "".join("    " + ln + "\n" for ln in foreground_xml().rstrip("\n").split("\n"))
           + "    </group>\n")
    return bg + grp


# --- raster drawing (Pillow, 4x supersampling) ------------------------------------------------
SS = 4


def draw_keyboard(d, ox, oy, scale):
    def rr(x, y, w, h, r, fill):
        d.rounded_rectangle([ox + x * scale, oy + y * scale, ox + (x + w) * scale, oy + (y + h) * scale],
                            radius=r * scale, fill=fill)
    rr(*BODY_RECT, BODY)
    for kk in keys():
        rr(*kk[:5], FOCUS if kk[5] == "focus" else KEY)


def render_icon(size, rounded=True):
    n = size * SS
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    s = n / 108.0
    if rounded:
        d.rounded_rectangle([0, 0, n - 1, n - 1], radius=24 * s, fill=BG)
    else:
        d.rectangle([0, 0, n, n], fill=BG)
    k = 1.3
    draw_keyboard(d, (54 - 54 * k) * s, (54 - 54 * k) * s, s * k)
    return img.resize((size, size), Image.LANCZOS)


def font(size):
    for p in ("/usr/share/fonts/truetype/google-fonts/Poppins-Bold.ttf",
              "/usr/share/fonts/truetype/lato/Lato-Bold.ttf",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"):
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()


def render_banner(w=640, h=360):
    W, H = w * SS, h * SS
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)
    # soft vertical gradient: slightly lighter at the top
    top, bot = (0x1C, 0x2D, 0x3C), (0x12, 0x1B, 0x25)
    for y in range(H):
        t = y / (H - 1)
        d.line([(0, y), (W, y)], fill=tuple(int(top[i] + (bot[i] - top[i]) * t) for i in range(3)))
    # keyboard glyph, centred in the upper part
    kscale = (h * SS * 0.50) / 34.0 * 1.0          # body height ~ 0.5 of banner height / 34 units
    bw, bh = BODY_RECT[2] * kscale, BODY_RECT[3] * kscale
    ox = (W - bw) / 2 - BODY_RECT[0] * kscale
    oy = 38 * SS - BODY_RECT[1] * kscale
    draw_keyboard(d, ox, oy, kscale)
    # title
    f = font(46 * SS)
    text = "Simple Keyboard TV"
    tw = d.textlength(text, font=f)
    ty = oy + (BODY_RECT[1] + BODY_RECT[3]) * kscale + 26 * SS
    d.text(((W - tw) / 2, ty), text, font=f, fill="#FFFFFF")
    # accent bar
    d.rectangle([0, H - 8 * SS, W, H], fill=ACCENT)
    return img.resize((w, h), Image.LANCZOS)


def svg_icon():
    p = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">',
         f'<rect width="108" height="108" rx="24" fill="{BG}"/>',
         '<g transform="translate(-16.2 -16.2) scale(1.3)">',
         f'<path d="{rrect_path(*BODY_RECT)}" fill="{BODY}"/>']
    p.append(f'<path d="{"".join(rrect_path(*k[:5]) for k in keys() if k[5] == "key")}" fill="{KEY}"/>')
    p.append(f'<path d="{"".join(rrect_path(*k[:5]) for k in keys() if k[5] == "focus")}" fill="{FOCUS}"/>')
    p.append("</g></svg>\n")
    return "\n".join(p)


def write(path, text, mode="w"):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, mode, **({"encoding": "utf-8", "newline": "\n"} if "b" not in mode else {})) as fh:
        fh.write(text)
    print("wrote", path)


def main():
    write("app/src/main/res/drawable-v26/ic_launcher_foreground.xml", vector(108, foreground_xml()))
    write("app/src/main/res/drawable-v26/ic_launcher_monochrome.xml", vector(108, monochrome_xml()))
    write("app/src/main/res/drawable/ic_launcher.xml", vector(108, legacy_xml()))
    write("icons/icon.svg", svg_icon())
    banner = render_banner()
    for rel, im in (("app/src/main/res/drawable-xhdpi/ic_banner.png", banner),
                    ("icons/banner.png", banner),
                    ("icons/icon-512.png", render_icon(512))):
        full = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        im.save(full, optimize=True)
        print("wrote", rel)


if __name__ == "__main__":
    sys.exit(main())
